function t(key) {
  const table = STRINGS[typeof LOCALE === 'string' ? LOCALE : 'en'] || STRINGS.en;
  return table[key] ?? STRINGS.en[key] ?? key;
}

/** Fill `data-i18n` (text) and `data-i18n-title` / `data-i18n-placeholder` attributes. */
function applyI18n(root) {
  // The language picks the glyphs of the CJK fonts (popup.html).
  if (root.documentElement) root.documentElement.lang = typeof LOCALE === 'string' ? LOCALE : 'en';
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
}
